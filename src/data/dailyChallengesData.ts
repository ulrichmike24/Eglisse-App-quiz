/**
 * Returns the daily challenge for today or cycles through available challenges
 */
export function getTodayChallenge(date = new Date()): DailyReadingChallenge {
  const dateStr = date.toISOString().split('T')[0];
  const exact = DAILY_READING_CHALLENGES.find((c) => c.dateStr === dateStr);
  if (exact) return exact;

  // Use day of year modulo count as deterministic fallback
  const startOfYear = new Date(date.getFullYear(), 0, 1);
  const diff = date.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  const index = Math.abs(dayOfYear) % DAILY_READING_CHALLENGES.length;
  const picked = DAILY_READING_CHALLENGES[index];

  return {
    ...picked,
    dateStr,
    dayOfYear,
  };
}
